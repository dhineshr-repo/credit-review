drop table cr_financial_anomalies cascade constraints;
drop table cr_credit_reviews cascade constraints;
drop table cr_customers cascade constraints;

-- Customers Master Table
create table cr_customers (
    id                     number generated by default on null as identity
                           constraint cr_customers_id_pk primary key,
    company_name           varchar2(150 char) constraint cr_cust_name_nn not null
                           constraint cr_cust_name_unq unique,
    duns_number            varchar2(20 char) constraint cr_cust_duns_unq unique,
    industry               varchar2(60 char) constraint cr_cust_ind_chk
                           check (industry in ('Technology','Healthcare','Manufacturing','Financial_Services','Retail','Energy')),
    annual_revenue         number(14,2),
    years_in_business      number(4),
    country                varchar2(50 char),
    primary_contact_name   varchar2(100 char),
    primary_contact_email  varchar2(120 char),
    current_credit_limit   number(12,2) default 0,
    requested_credit_limit number(12,2) default 0,
    credit_score           number(3) constraint cr_cust_score_chk check (credit_score between 300 and 850),
    risk_category          varchar2(20 char) constraint cr_cust_risk_chk
                           check (risk_category in ('Low_Risk','Moderate_Risk','High_Risk','Severe_Risk')),
    payment_behavior_score number(3) constraint cr_cust_pay_chk check (payment_behavior_score between 0 and 100),
    bankruptcy_flag        varchar2(1 char) default 'N' constraint cr_cust_bankr_chk check (bankruptcy_flag in ('Y','N')),
    outstanding_balance    number(12,2) default 0,
    overdue_amount         number(12,2) default 0,
    days_sales_outstanding number(3) default 30,
    review_status          varchar2(30 char) default 'Pending_Analyst' constraint cr_cust_rev_chk
                           check (review_status in ('Draft','Pending_Analyst','Committee_Review','Approved','Rejected','Conditional')),
    ai_risk_summary        clob,
    created                date not null,
    created_by             varchar2(255 char) not null,
    updated                date not null,
    updated_by             varchar2(255 char) not null
);

create or replace trigger cr_customers_biu
    before insert or update on cr_customers
    for each row
begin
    if inserting then
        :new.created    := sysdate;
        :new.created_by := coalesce(sys_context('APEX$SESSION','APP_USER'), user);
    end if;
    :new.updated    := sysdate;
    :new.updated_by := coalesce(sys_context('APEX$SESSION','APP_USER'), user);
end;
/

-- Credit Review Underwriting Table
create table cr_credit_reviews (
    id                         number generated by default on null as identity
                               constraint cr_reviews_id_pk primary key,
    customer_id                number constraint cr_rev_cust_fk
                               references cr_customers on delete cascade,
    review_date                date default sysdate not null,
    analyst_name               varchar2(100 char),
    proposed_credit_limit      number(12,2),
    recommended_action         varchar2(30 char) constraint cr_rev_act_chk
                               check (recommended_action in ('Approve_Limit','Maintain_Limit','Reduce_Limit','Require_Collateral','Reject')),
    payment_terms              varchar2(30 char) constraint cr_rev_terms_chk
                               check (payment_terms in ('Net_30','Net_45','Net_60','Letter_of_Credit','Prepayment')),
    financial_statement_rating varchar2(10 char) constraint cr_rev_fs_chk
                               check (financial_statement_rating in ('Strong','Satisfactory','Weak','Distressed')),
    collateral_value           number(12,2) default 0,
    review_notes               clob,
    approval_status            varchar2(20 char) default 'Pending' constraint cr_rev_app_chk
                               check (approval_status in ('Pending','Approved','Rejected','Escalated')),
    created                    date not null,
    created_by                 varchar2(255 char) not null,
    updated                    date not null,
    updated_by                 varchar2(255 char) not null
);

create or replace trigger cr_credit_reviews_biu
    before insert or update on cr_credit_reviews
    for each row
begin
    if inserting then
        :new.created    := sysdate;
        :new.created_by := coalesce(sys_context('APEX$SESSION','APP_USER'), user);
    end if;
    :new.updated    := sysdate;
    :new.updated_by := coalesce(sys_context('APEX$SESSION','APP_USER'), user);
end;
/

-- Financial Anomalies & Risk Triggers Table
create table cr_financial_anomalies (
    id                number generated by default on null as identity
                      constraint cr_anomalies_id_pk primary key,
    customer_id       number constraint cr_anom_cust_fk
                      references cr_customers on delete cascade,
    detected_date     date default sysdate not null,
    anomaly_type      varchar2(50 char) constraint cr_anom_type_chk
                      check (anomaly_type in ('Late_Payment_Trend','Credit_Bureau_Downgrade','DSO_Spike','Adverse_Media','Revenue_Decline')),
    severity          varchar2(10 char) constraint cr_anom_sev_chk
                      check (severity in ('Critical','High','Medium','Low')),
    impact_score      number(3) constraint cr_anom_score_chk check (impact_score between 0 and 100),
    alert_description varchar2(500 char) not null,
    status            varchar2(20 char) default 'Open' constraint cr_anom_stat_chk
                      check (status in ('Open','Under_Investigation','Resolved','False_Positive')),
    created           date not null,
    created_by        varchar2(255 char) not null,
    updated           date not null,
    updated_by        varchar2(255 char) not null
);

create or replace trigger cr_financial_anomalies_biu
    before insert or update on cr_financial_anomalies
    for each row
begin
    if inserting then
        :new.created    := sysdate;
        :new.created_by := coalesce(sys_context('APEX$SESSION','APP_USER'), user);
    end if;
    :new.updated    := sysdate;
    :new.updated_by := coalesce(sys_context('APEX$SESSION','APP_USER'), user);
end;
/

